<#
.SYNOPSIS
  Opens the files generated by browser/demo.html and browser/test.html in
  Microsoft Excel and verifies that every feature survived the round trip.

.DESCRIPTION
  The manifest is produced by full-features.test.ts after running both pages.
  Each file entry can request:
    sheetCount / allSheetsAutofilter / sheets
  and each sheet entry can request:
    tables, cf, cfPriorities, cfFill, comments, protected, allowInsertRows,
    autofilter, usedRowsMin, validations, tableChecks.

  Results are written as a JSON array. Exit code 1 when a check fails.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)][string] $ManifestPath,
    [Parameter(Mandatory)][string] $OutPath
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$manifest = Get-Content -LiteralPath $ManifestPath -Raw -Encoding UTF8 | ConvertFrom-Json
$results = New-Object System.Collections.ArrayList

function Add-Result {
    param(
        [string] $File,
        [string] $Sheet = '',
        [string] $Check,
        [bool] $Pass,
        $Expected,
        $Actual,
        [string] $Message = ''
    )
    [void]$results.Add([pscustomobject]@{
        file     = $File
        sheet    = $Sheet
        check    = $Check
        pass     = $Pass
        expected = if ($null -eq $Expected) { $null } else { [string]$Expected }
        actual   = if ($null -eq $Actual) { $null } else { [string]$Actual }
        message  = $Message
    })
}

function Get-Property {
    param($Object, [string] $Name)
    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) { return $null }
    return $property.Value
}

function Check-Value {
    param([string] $File, [string] $Sheet, [string] $Check, $Expected, $Actual)
    Add-Result $File $Sheet $Check ([string]$Expected -ceq [string]$Actual) $Expected $Actual
}

function Test-Validation {
    param([string] $File, $Worksheet, $Spec)
    $cell = [string]$Spec.cell
    $validation = $null
    try {
        $validation = $Worksheet.Range($cell).Validation
    } catch {
        Add-Result $File ([string]$Worksheet.Name) "validation:$cell" $false 'validation object' 'error' $_.Exception.Message
        return
    }
    $type = Get-Property $Spec 'type'
    if ($null -ne $type) {
        Check-Value $File ([string]$Worksheet.Name) "validation:$cell.type" $type ([int]$validation.Type)
    }
    $operator = Get-Property $Spec 'operator'
    if ($null -ne $operator) {
        Check-Value $File ([string]$Worksheet.Name) "validation:$cell.operator" $operator ([int]$validation.Operator)
    }
    $formula = Get-Property $Spec 'formula1'
    if ($null -ne $formula) {
        Check-Value $File ([string]$Worksheet.Name) "validation:$cell.formula1" $formula ([string]$validation.Formula1)
    }
}

function Test-Table {
    param([string] $File, $Worksheet, $Spec)
    $name = [string]$Spec.name
    $table = $null
    try {
        $table = $Worksheet.ListObjects.Item($name)
    } catch {
        Add-Result $File ([string]$Worksheet.Name) "table:$name" $false 'table exists' 'missing'
        return
    }
    Add-Result $File ([string]$Worksheet.Name) "table:$name" $true 'table exists' 'present'
    $showTotals = Get-Property $Spec 'showTotals'
    if ($null -ne $showTotals) {
        Check-Value $File ([string]$Worksheet.Name) "table:$name.showTotals" $showTotals ([bool]$table.ShowTotals)
    }
    foreach ($total in @(Get-Property $Spec 'totals')) {
        if ($null -eq $total) { continue }
        $column = [int]$total.column
        $expectedFormula = [string]$total.formula
        $actualFormula = [string]$table.TotalsRowRange.Cells.Item(1, $column).Formula
        Check-Value $File ([string]$Worksheet.Name) "table:$name.total:$column" $expectedFormula $actualFormula
    }
}

function Test-CellStyle {
    param([string] $File, $Worksheet, $Spec)
    $cell = [string]$Spec.cell
    $range = $Worksheet.Range($cell)
    $name = [string]$Worksheet.Name

    $fontName = Get-Property $Spec 'fontName'
    if ($null -ne $fontName) {
        Check-Value $File $name "style:$cell.fontName" $fontName ([string]$range.Font.Name)
    }
    $gradientStops = Get-Property $Spec 'gradientStops'
    if ($null -ne $gradientStops) {
        Check-Value $File $name "style:$cell.gradientStops" $gradientStops ([int]$range.Interior.Gradient.ColorStops.Count)
    }
    $pattern = Get-Property $Spec 'pattern'
    if ($null -ne $pattern) {
        Check-Value $File $name "style:$cell.pattern" $pattern ([int]$range.Interior.Pattern)
    }
    $locked = Get-Property $Spec 'locked'
    if ($null -ne $locked) {
        Check-Value $File $name "style:$cell.locked" $locked ([bool]$range.Locked)
    }
    $formulaHidden = Get-Property $Spec 'formulaHidden'
    if ($null -ne $formulaHidden) {
        Check-Value $File $name "style:$cell.formulaHidden" $formulaHidden ([bool]$range.FormulaHidden)
    }
    $indent = Get-Property $Spec 'indent'
    if ($null -ne $indent) {
        Check-Value $File $name "style:$cell.indent" $indent ([int]$range.IndentLevel)
    }
}

function Test-Sheet {
    param([string] $File, $Workbook, $Spec, [bool] $AllSheetsAutofilter)
    $name = [string]$Spec.name
    $worksheet = $null
    try {
        $worksheet = $Workbook.Worksheets.Item($name)
    } catch {
        Add-Result $File $name 'sheet' $false 'sheet exists' 'missing'
        return
    }
    Add-Result $File $name 'sheet' $true 'sheet exists' 'present'

    foreach ($pair in @(
        @('tables', { $worksheet.ListObjects.Count }),
        @('cf', { $worksheet.Cells.FormatConditions.Count }),
        @('comments', { $worksheet.Comments.Count })
    )) {
        $key = [string]$pair[0]
        $expected = Get-Property $Spec $key
        if ($null -ne $expected) {
            $actual = & $pair[1]
            Check-Value $File $name $key $expected $actual
        }
    }

    $expectedProtected = Get-Property $Spec 'protected'
    if ($null -ne $expectedProtected) {
        Check-Value $File $name 'protected' $expectedProtected ([bool]$worksheet.ProtectContents)
    }
    $expectedInsertRows = Get-Property $Spec 'allowInsertRows'
    if ($null -ne $expectedInsertRows) {
        Check-Value $File $name 'allowInsertRows' $expectedInsertRows ([bool]$worksheet.Protection.AllowInsertingRows)
    }
    $expectedFilter = Get-Property $Spec 'autofilter'
    if ($null -ne $expectedFilter) {
        Check-Value $File $name 'autofilter' $expectedFilter ([bool]$worksheet.AutoFilterMode)
    }
    $expectedFont = Get-Property $Spec 'fontName'
    if ($null -ne $expectedFont) {
        Check-Value $File $name 'fontName' $expectedFont ([string]$worksheet.Range('A1').Font.Name)
    }
    if ($AllSheetsAutofilter) {
        Check-Value $File $name 'autofilter:all' $true ([bool]$worksheet.AutoFilterMode)
    }
    $expectedRows = Get-Property $Spec 'usedRowsMin'
    if ($null -ne $expectedRows) {
        $actualRows = [int]$worksheet.UsedRange.Rows.Count
        Add-Result $File $name 'usedRowsMin' ($actualRows -ge [int]$expectedRows) ">= $expectedRows" $actualRows
    }

    $conditions = $null
    if ((Get-Property $Spec 'cfPriorities') -eq $true) {
        $conditions = $worksheet.Cells.FormatConditions
        $priorities = @()
        for ($i = 1; $i -le [int]$conditions.Count; $i++) {
            $priorities += [int]$conditions.Item($i).Priority
        }
        $sorted = @($priorities | Sort-Object)
        $expected = @(1..$sorted.Count) -join ','
        Check-Value $File $name 'cfPriorities' $expected ($sorted -join ',')
    }
    $expectedFill = Get-Property $Spec 'cfFill'
    if ($null -ne $expectedFill) {
        if ($null -eq $conditions) { $conditions = $worksheet.Cells.FormatConditions }
        $actualFill = [int]$conditions.Item(1).Interior.Color
        Check-Value $File $name 'cfFill' $expectedFill $actualFill
    }

    foreach ($validation in @(Get-Property $Spec 'validations')) {
        if ($null -eq $validation) { continue }
        Test-Validation $File $worksheet $validation
    }
    foreach ($table in @(Get-Property $Spec 'tableChecks')) {
        if ($null -eq $table) { continue }
        Test-Table $File $worksheet $table
    }
    foreach ($style in @(Get-Property $Spec 'styleChecks')) {
        if ($null -eq $style) { continue }
        Test-CellStyle $File $worksheet $style
    }
}

$excel = $null
try {
    $excel = New-Object -ComObject Excel.Application
    $excel.Visible = $false
    $excel.DisplayAlerts = $false
    $excel.ScreenUpdating = $false
    $excel.AutomationSecurity = 3

    foreach ($entry in @($manifest.files)) {
        $label = [string]$entry.label
        $path = [string]$entry.path
        $workbook = $null
        try {
            $workbook = $excel.Workbooks.Open($path, 0, $true)
        } catch {
            Add-Result $label '' 'open' $false 'opens in Excel' 'error' $_.Exception.Message
            continue
        }
        Add-Result $label '' 'open' $true 'opens in Excel' 'opened'

        try {
            $sheetCount = Get-Property $entry 'sheetCount'
            if ($null -ne $sheetCount) {
                Check-Value $label '' 'sheetCount' $sheetCount ([int]$workbook.Worksheets.Count)
            }

            $expectedSheets = @(Get-Property $entry 'sheets')
            if ($expectedSheets.Count -gt 0) {
                $actualNames = @()
                for ($i = 1; $i -le [int]$workbook.Worksheets.Count; $i++) {
                    $actualNames += [string]$workbook.Worksheets.Item($i).Name
                }
                $expectedNames = @($expectedSheets | ForEach-Object { [string]$_.name })
                $namesOk = ($actualNames.Count -eq $expectedNames.Count)
                if ($namesOk) {
                    for ($i = 0; $i -lt $expectedNames.Count; $i++) {
                        if ($actualNames[$i] -cne $expectedNames[$i]) { $namesOk = $false; break }
                    }
                }
                Add-Result $label '' 'sheetNames' $namesOk ($expectedNames -join ', ') ($actualNames -join ', ')
                $allFilter = (Get-Property $entry 'allSheetsAutofilter') -eq $true
                foreach ($sheetSpec in $expectedSheets) {
                    Test-Sheet $label $workbook $sheetSpec $allFilter
                }
            }
        } catch {
            Add-Result $label '' 'inspect' $false 'inspection completes' 'exception' $_.Exception.Message
        } finally {
            if ($workbook) { try { $workbook.Close($false) } catch { } }
        }
    }
}
finally {
    if ($excel) {
        try { $excel.Quit() } catch { }
        [void][System.Runtime.InteropServices.Marshal]::ReleaseComObject($excel)
    }
    [GC]::Collect(); [GC]::WaitForPendingFinalizers()
}

$json = ConvertTo-Json -InputObject @($results) -Depth 5
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($OutPath), $json, [System.Text.UTF8Encoding]::new($false))
$failed = @($results | Where-Object { -not $_.pass }).Count
Write-Host "Generated-file Excel verify: $($results.Count - $failed) passed, $failed failed"
if ($failed -gt 0) { exit 1 }
